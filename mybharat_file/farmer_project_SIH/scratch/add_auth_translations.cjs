// Now let's inject new keys into each language object in translations.ts
// Format in translations.ts:
// export const TRANSLATIONS: Record<Language, TranslationDictionary> = {
//   en: { ... },
//   gu: { ... },
//   hi: { ... },
//   mr: { ... },
// };

function injectKeys(langCode, keysObj) {
  const regex = new RegExp(`(\\s+${langCode}:\\s*\\{[\\s\\S]*?)(\\n\\s+\\},?\\n(?:\\};)?)`, 'm');
  const match = content.match(regex);
  if (!match) {
    console.error(`Could not find dictionary for ${langCode}`);
    return;
  }

  let injection = '';
  for (const [k, v] of Object.entries(keysObj)) {
    // Only add if not already present
    if (!match[1].includes(`'${k}':`)) {
      const escapedVal = v.replace(/'/g, "\\'");
      injection += `    '${k}': '${escapedVal}',\n`;
    }
  }

  if (injection) {
    content = content.replace(regex, `$1\n${injection}$2`);
    console.log(`Injected keys into ${langCode}`);
  } else {
    console.log(`Keys already present in ${langCode}`);
  }
}

